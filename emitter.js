// emitter — turns a scaffold plan + scan into actual files on disk.
// offline renderer: builds substantive, grounded content from the scan with no
// LLM. the goal is a RICH context pack, not a thin stub — every doc pulls real
// facts (stack, structure, commands, env, config, evidence). an LLM prose pass
// can be layered on top later, but this alone must be useful.
const fs = require('fs');
const path = require('path');

const known = (v) => v && v !== 'unknown';
const code = (s) => '`' + s + '`';

// ---- individual doc renderers ---------------------------------------------

function renderEntry(scan, plan, layout = { docDir: '', skillDir: 'skills' }) {
  const docLink = (name) => (layout.docDir ? `./${layout.docDir}/${name}` : `./${name}`);
  const skillLink = (name) => `./${layout.skillDir}/${name}/SKILL.md`;
  const L = [];
  L.push('# Agent Context Pack');
  L.push('');
  L.push('> Generated by Razor from a repository scan. Every section is grounded');
  L.push('> in files that were actually found — see the evidence notes.');
  L.push('');
  L.push('This is the entry point. Load the linked docs and skills on demand —');
  L.push('you do not need all of them for every task.');
  L.push('');
  if (scan.readme_summary) {
    L.push(`**What this repo is:** ${scan.readme_summary}`);
    L.push('');
  }
  if (known(scan.language) || known(scan.framework)) {
    L.push(`**Stack:** ${[scan.language, scan.framework].filter(known).join(' / ')}`);
    L.push('');
  }

  L.push('## Documents');
  for (const d of plan.docs) {
    L.push(`- [\`${d.name}.md\`](${docLink(`${d.name}.md`)}) — ${d.reason}`);
  }
  L.push('');

  if (plan.skills.length) {
    L.push('## Skills (load when the task matches)');
    for (const s of plan.skills) {
      L.push(`- [\`${s.name}\`](${skillLink(s.name)}) — ${s.intent}`);
    }
    L.push('');
  }

  if (plan.script) {
    L.push('## Verification script');
    L.push(`- ${code(plan.script.file)} — run this to check your work.`);
    L.push('');
  }

  L.push('## Ground rules');
  L.push('- Only follow conventions that are stated here or evident in the code.');
  L.push('- Prefer the existing commands and tools below over introducing new ones.');
  L.push('- Run the verification steps before considering a task done.');
  L.push('');
  return L.join('\n');
}

function renderOverview(scan, flows = {}) {
  const L = [];
  L.push('# Overview');
  L.push('');
  if (scan.readme_summary) { L.push(scan.readme_summary); L.push(''); }

  L.push('## Stack');
  if (known(scan.language)) L.push(`- Language: ${scan.language}`);
  if (known(scan.framework)) L.push(`- Framework: ${scan.framework}`);
  if (flows.buildSystem) L.push(`- Build system: ${flows.buildSystem}`);
  if (known(scan.testing)) L.push(`- Testing: ${scan.testing}`);
  if (known(scan.orm)) L.push(`- ORM / data layer: ${scan.orm}`);
  if (known(scan.package_manager)) L.push(`- Package manager: ${scan.package_manager}`);
  if (known(scan.entry_point)) L.push(`- Entry point: ${code(scan.entry_point)}`);
  L.push('');

  if (scan.key_dependencies && scan.key_dependencies.length) {
    L.push('## Key dependencies');
    L.push(scan.key_dependencies.map(code).join(', '));
    L.push('');
  }

  if (scan.sub_projects && scan.sub_projects.length) {
    L.push('## Sub-projects');
    for (const sp of scan.sub_projects) {
      L.push(`- ${code(sp.path)} — ${[sp.language, sp.framework].filter(known).join(' / ')}`);
    }
    L.push('');
  }

  L.push('## How to run');
  const scripts = scan.scripts || {};
  if (scripts.dev) L.push(`- Dev: ${code(scripts.dev)}`);
  else if (scripts.start) L.push(`- Start: ${code(scripts.start)}`);
  else if (known(scan.entry_point)) L.push(`- Entry point is ${code(scan.entry_point)} — run it with the appropriate runtime.`);
  if (scripts.build) L.push(`- Build: ${code(scripts.build)}`);
  else if (flows.buildCommand) L.push(`- Build: ${code(flows.buildCommand)}`);
  L.push('');
  return L.join('\n');
}

function renderArchitecture(scan) {
  const L = [];
  L.push('# Architecture');
  L.push('');
  L.push('How the code is organized. Based on the detected directory layout.');
  L.push('');
  if (scan.structure && scan.structure.length) {
    L.push('## Directory layout');
    for (const s of scan.structure) L.push(`- ${s}`);
    L.push('');
  }
  if (known(scan.routes_folder)) {
    L.push('## Routing');
    L.push(`- Route handlers live in ${code(scan.routes_folder)}. Put new endpoints there.`);
    L.push('');
  }
  if (scan.sub_projects && scan.sub_projects.length) {
    L.push('## Sub-projects');
    L.push('This repo contains more than one project:');
    for (const sp of scan.sub_projects) {
      L.push(`- ${code(sp.path)} — ${[sp.language, sp.framework].filter(known).join(' / ')}`);
    }
    L.push('');
    L.push('> Note: per-sub-project tooling may differ; check each one before changing it.');
    L.push('');
  }
  return L.join('\n');
}

function renderWorkflows(scan, flows) {
  const L = [];
  L.push('# Workflows');
  L.push('');
  L.push('Common development workflows, using the repo\'s real commands.');
  L.push('');
  const scripts = scan.scripts || {};
  if (Object.keys(scripts).length) {
    L.push('## Available scripts');
    for (const [k, v] of Object.entries(scripts)) L.push(`- ${code(k)}: ${code(v)}`);
    L.push('');
  }
  if (flows.buildSystem) {
    L.push('## Build');
    L.push(`- Build system: ${flows.buildSystem} (${flows.evidence.build_system}).`);
    if (flows.buildCommand) L.push(`- Build: ${code(flows.buildCommand)}`);
    if (flows.testCommand) L.push(`- Test: ${code(flows.testCommand)}`);
    L.push(`- Prefer ${flows.buildSystem} over compiling or running files directly.`);
    L.push('');
  }
  if (flows.hasCI) {
    L.push('## CI');
    L.push(`- CI is configured (${flows.evidence.ci}). Changes should keep CI green.`);
    L.push('');
  }
  if (flows.hasDocker) {
    L.push('## Containers');
    L.push(`- Docker is present (${flows.evidence.docker}). Use it for a reproducible local env.`);
    L.push('');
  }
  if (flows.hasMigrations) {
    L.push('## Database migrations');
    L.push(`- Migrations exist (${flows.evidence.migrations}). See the db-migrations skill.`);
    L.push('');
  }
  return L.join('\n');
}

function renderVerification(scan, flows, plan) {
  const L = [];
  L.push('# Verification');
  L.push('');
  L.push('How to check that work is correct before calling a task done.');
  L.push('');
  const scripts = scan.scripts || {};
  L.push('## Checks');
  if (scripts.lint) L.push(`- Lint: ${code(scripts.lint)}`);
  else if (flows.hasLint) L.push(`- Lint config present (${flows.evidence.lint}) — run the project linter.`);
  if (scripts.test) L.push(`- Tests: ${code(scripts.test)}`);
  else if (flows.testCommand) L.push(`- Tests: ${code(flows.testCommand)} (${flows.buildSystem}).`);
  else if (known(scan.testing)) L.push(`- Tests use ${scan.testing} — run the suite.`);
  if (scripts.typecheck) L.push(`- Typecheck: ${code(scripts.typecheck)}`);
  if (L[L.length - 1] === '## Checks') L.push('- No automated checks detected — verify changes manually.');
  L.push('');
  if (plan.script) {
    L.push('## One-shot');
    L.push(`- Run ${code(plan.script.file)} to do lint + test in one go.`);
    L.push('');
  }
  if (scan.test_locations && scan.test_locations.length) {
    L.push('## Where tests live');
    L.push(scan.test_locations.map(code).join(', '));
    L.push('');
  }
  return L.join('\n');
}

function renderSteering(scan, flows) {
  const L = [];
  L.push('# Steering');
  L.push('');
  L.push('Global conventions for this repo. Kept short on purpose.');
  L.push('');
  if (known(scan.testing)) L.push(`- Write tests with ${scan.testing}. Do not add other test runners.`);
  if (known(scan.orm)) L.push(`- Use ${scan.orm} for database access. Do not write raw SQL.`);
  if (known(scan.routes_folder)) L.push(`- Put route handlers in ${code(scan.routes_folder)}.`);
  if (flows.hasLint) L.push('- Match the existing lint/format config; do not reformat unrelated code.');
  if (scan.config_files && scan.config_files.length) {
    L.push(`- Respect existing config: ${scan.config_files.map(code).join(', ')}.`);
  }
  if (scan.env_vars && scan.env_vars.length) {
    L.push(`- Required env vars (names only): ${scan.env_vars.map(code).join(', ')}.`);
  }
  if (L[L.length - 1] === '') L.pop();
  if (L[L.length - 1] === 'Global conventions for this repo. Kept short on purpose.') {
    L.push('');
    L.push('- (no specific conventions detected)');
  }
  L.push('');
  return L.join('\n');
}

// ---- skill renderers ------------------------------------------------------

function renderSkill(skill, scan) {
  const L = [];
  // frontmatter — name + description is the discoverability contract
  L.push('---');
  L.push(`name: ${skill.name}`);
  L.push(`description: ${skillDescription(skill)}`);
  L.push('---');
  L.push('');
  L.push(`# ${skill.name}`);
  L.push('');
  L.push(`> Evidence: ${skill.evidence || 'n/a'}`);
  L.push('');
  L.push('## Steps');
  L.push(...skillSteps(skill, scan));
  L.push('');
  return L.join('\n');
}

function skillDescription(skill) {
  const map = {
    'run-tests': `Run the test suite (${skill.framework || 'detected test runner'}). Use when verifying changes or before pushing.`,
    'lint-fix': 'Lint and auto-fix code style. Use before committing to keep CI green.',
    'code-push': 'Verify then push changes to the remote. Use when the user asks to commit/push/open a PR.',
    'db-migrations': `Create and apply database migrations (${skill.orm || 'detected ORM'}). Use when changing the data model.`,
    'local-env': 'Build and run the app locally with containers. Use to spin up a reproducible dev environment.',
    build: `Build the project with ${skill.buildSystem || 'the detected build system'}. Use before running or testing.`,
  };
  return map[skill.name] || skill.intent;
}

function skillSteps(skill, scan) {
  const S = [];
  switch (skill.name) {
    case 'run-tests':
      if (skill.command) S.push(`1. Run ${code(skill.command)}.`);
      else S.push(`1. Run the ${skill.framework || 'project'} test suite.`);
      S.push('2. Fix failures before continuing. Do not disable or skip tests to make them pass.');
      break;
    case 'lint-fix':
      if (skill.command) S.push(`1. Run ${code(skill.command)} (add the fix flag if the linter supports it).`);
      else S.push('1. Run the project linter/formatter.');
      S.push('2. Only fix issues in files you changed; do not reformat unrelated code.');
      break;
    case 'code-push':
      if (skill.verify && skill.verify.length) {
        S.push(`1. Verify first: ${skill.verify.map(code).join(' , ')}.`);
      } else {
        S.push('1. Verify your changes (run tests/lint if available).');
      }
      S.push('2. Stage only the files you intended to change.');
      S.push('3. Commit with a clear message, then push to the remote branch.');
      if (skill.hasCI) S.push('4. CI is configured — make sure it stays green after the push.');
      break;
    case 'db-migrations':
      if (skill.command) S.push(`1. Generate/apply migrations with ${code(skill.command)}.`);
      else S.push(`1. Use ${skill.orm || 'the ORM'}'s migration tool to generate and apply migrations.`);
      S.push('2. Never edit the database schema by hand — go through a migration.');
      S.push('3. Review the generated migration before applying it.');
      break;
    case 'local-env':
      S.push('1. Build the image / bring the stack up (see the Dockerfile / compose file).');
      S.push('2. Use the containerized env rather than installing services globally.');
      break;
    case 'build':
      if (skill.command) S.push(`1. Build with ${code(skill.command)}.`);
      else S.push(`1. Build the project using ${skill.buildSystem || 'the project build system'}.`);
      if (skill.testCommand) S.push(`2. Run tests with ${code(skill.testCommand)}.`);
      S.push(`${skill.testCommand ? 3 : 2}. Use ${skill.buildSystem || 'the build system'} rather than compiling files by hand.`);
      break;
    default:
      S.push(`1. ${skill.intent}.`);
  }
  return S;
}

// deeper reference doc for complex skills
function renderSkillReference(skill, scan) {
  const L = [];
  L.push(`# ${skill.name} — reference`);
  L.push('');
  L.push('Extra context for this skill (loaded only when needed).');
  L.push('');
  L.push(`> Evidence: ${skill.evidence || 'n/a'}`);
  L.push('');
  if (skill.name === 'db-migrations') {
    L.push(`- ORM in use: ${skill.orm || 'unknown'}.`);
    if (scan.env_vars && scan.env_vars.length) {
      const dbVars = scan.env_vars.filter((v) => /DB|DATABASE|POSTGRES|MYSQL|MONGO/i.test(v));
      if (dbVars.length) L.push(`- DB-related env vars: ${dbVars.map(code).join(', ')}.`);
    }
    L.push('- Always run migrations in a transaction where the tool supports it.');
    L.push('- Keep a rollback path; test the migration on a scratch DB before prod.');
  }
  L.push('');
  return L.join('\n');
}

function renderCheckScript(plan) {
  const L = [];
  L.push('#!/usr/bin/env bash');
  L.push('# generated by razor — run the repo\'s real verification steps');
  L.push('set -euo pipefail');
  L.push('');
  for (const step of plan.script.steps) L.push(step);
  L.push('');
  return L.join('\n');
}

// ---- main emit ------------------------------------------------------------

const DOC_RENDERERS = {
  overview: (scan, flows) => renderOverview(scan, flows),
  architecture: (scan) => renderArchitecture(scan),
  workflows: (scan, flows) => renderWorkflows(scan, flows),
  verification: (scan, flows, plan) => renderVerification(scan, flows, plan),
  steering: (scan, flows) => renderSteering(scan, flows),
};

// build the prose/doc drafts as a { name: markdown } map (no disk writes).
// this is the deterministic ground truth the enricher may refine.
function buildDocDrafts(scan, flows, plan) {
  const drafts = {};
  for (const d of plan.docs) {
    const r = DOC_RENDERERS[d.name];
    if (r) drafts[d.name] = r(scan, flows, plan);
  }
  return drafts;
}

// where each target brand expects files. verified against tool docs ~Oct 2026:
// - agents-md: the open standard, read by most tools out of the box.
// - kiro: steering under .kiro/steering/, skills under .kiro/skills/.
// - claude: AGENTS.md at root (Claude Code 2.1.277+ reads it when no CLAUDE.md),
//           skills under .claude/skills/ so Claude auto-discovers them.
// each returns relative paths within outDir.
function layoutFor(target) {
  switch (target) {
    case 'kiro':
      return {
        entry: 'AGENTS.md',
        docDir: '.kiro/steering',   // kiro auto-loads steering from here
        skillDir: '.kiro/skills',   // .kiro/skills/<name>/SKILL.md
        note: 'Kiro: steering under .kiro/steering/, skills under .kiro/skills/.',
      };
    case 'claude':
      return {
        entry: 'AGENTS.md',         // no bridge; Claude Code 2.1.277+ reads AGENTS.md
        docDir: '',                 // docs at root alongside the entry
        skillDir: '.claude/skills', // .claude/skills/<name>/SKILL.md
        note: 'Claude Code: AGENTS.md at root (needs v2.1.277+, no CLAUDE.md present); skills under .claude/skills/.',
      };
    case 'agents-md':
    default:
      return {
        entry: 'AGENTS.md',
        docDir: '',                 // docs at root
        skillDir: 'skills',         // skills/<name>/SKILL.md
        note: 'AGENTS.md open standard — read by Cursor, Codex, Copilot, Gemini CLI, Claude Code, and others.',
      };
  }
}

// write the whole scaffold to outDir. returns { written, note }.
// opts.docs (optional): a { name: markdown } map to use instead of re-rendering.
// opts.target: agents-md | kiro | claude  (controls file placement).
function emitScaffold(scan, flows, plan, outDir, opts = {}) {
  const layout = layoutFor(opts.target || 'agents-md');
  const docs = opts.docs || buildDocDrafts(scan, flows, plan);
  const written = [];
  const write = (rel, content) => {
    const full = path.join(outDir, rel);
    fs.mkdirSync(path.dirname(full), { recursive: true });
    fs.writeFileSync(full, content);
    written.push(rel);
  };
  const docPath = (name) => (layout.docDir ? path.join(layout.docDir, name) : name);

  // entry file (always at root so the tool finds it)
  write(layout.entry, renderEntry(scan, plan, layout));

  // top-level docs (enriched if provided, else deterministic draft)
  for (const d of plan.docs) {
    if (docs[d.name]) write(docPath(`${d.name}.md`), docs[d.name]);
  }

  // skills — always deterministic (they hold exact commands)
  for (const s of plan.skills) {
    write(path.join(layout.skillDir, s.name, 'SKILL.md'), renderSkill(s, scan));
    if (s.complex) {
      write(path.join(layout.skillDir, s.name, 'reference.md'), renderSkillReference(s, scan));
    }
  }

  // verification script
  if (plan.script) {
    write(plan.script.file, renderCheckScript(plan));
    try { fs.chmodSync(path.join(outDir, plan.script.file), 0o755); } catch (_) { /* ignore */ }
  }

  return { written, note: layout.note };
}

module.exports = {
  emitScaffold,
  buildDocDrafts,
  // exported for tests
  renderEntry, renderOverview, renderSkill, renderCheckScript,
};
